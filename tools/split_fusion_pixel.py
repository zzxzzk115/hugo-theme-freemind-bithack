"""Split the Fusion Pixel CJK font into frequency-based WOFF2 pieces so a page downloads only what it uses.

    pip install fonttools brotli
    python tools/split_fusion_pixel.py

Reads static/css/fonts/fusion-pixel/fusion-pixel-12px-proportional-zh_hans.otf.woff2 (the full font, which the
giscus theme still uses) and writes, next to it:
    fusion-pixel-12px-zh_hans.0.woff2   CJK punctuation, full-width forms + GB2312 level 1 (~3,700 common hanzi)
    fusion-pixel-12px-zh_hans.1.woff2   GB2312 level 2 (~3,000 less common hanzi)
    fusion-pixel-12px-zh_hans.2.woff2   everything else (rare hanzi, kana, radicals, ...)
    fusion-pixel-12px-latin.woff2       Latin, as the family "Fusion Pixel" (crisp small labels; body text stays Fixedsys)
and assets/css/fusion-pixel.css with the @font-face rules (registered as "DOS" and "Fira Code", the theme's
Latin pixel / code families, so CJK text in either gets pixels). Piece 2 is declared with the broad CJK ranges
and first, so pieces 0 and 1 (declared later) take priority for the characters they hold.
"""
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

THEME = Path(__file__).resolve().parent.parent
DIR = THEME / "static" / "css" / "fonts" / "fusion-pixel"
SRC = DIR / "fusion-pixel-12px-proportional-zh_hans.otf.woff2"
CSS = THEME / "assets" / "css" / "fusion-pixel.css"
FAMILIES = ["DOS", "Fira Code"]
CJK = [(0x2E80, 0x2FFF), (0x3000, 0x303F), (0x3040, 0x30FF), (0x3100, 0x312F), (0x3190, 0x31FF), (0x3200, 0x33FF),
       (0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0xFE10, 0xFE1F), (0xFE30, 0xFE4F), (0xFF00, 0xFFEF)]


def gb2312(first, last):
    out = set()
    for b1 in range(first, last + 1):
        for b2 in range(0xA1, 0xFF):
            try:
                out.add(ord(bytes([b1, b2]).decode("gb2312")))
            except UnicodeDecodeError:
                pass
    return out


def ranges(cps):
    cps = sorted(cps)
    spans, start, prev = [], cps[0], cps[0]
    for c in cps[1:]:
        if c != prev + 1:
            spans.append((start, prev))
            start = c
        prev = c
    spans.append((start, prev))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in spans)


def main():
    font = TTFont(SRC)
    cmap = set(font.getBestCmap())
    font.close()
    cjk = {c for c in cmap if any(a <= c <= b for a, b in CJK)}
    punct = {c for c in cjk if 0x3000 <= c <= 0x303F or 0xFE10 <= c <= 0xFE4F or 0xFF00 <= c <= 0xFFEF}
    p0 = (punct | gb2312(0xB0, 0xD7)) & cjk
    p1 = (gb2312(0xD8, 0xF7) & cjk) - p0
    p2 = cjk - p0 - p1
    broad = ",".join(f"U+{a:X}-{b:X}" for a, b in CJK)
    faces = []
    for i, cps, rng in [(2, p2, broad), (1, p1, ranges(p1)), (0, p0, ranges(p0))]:
        name = f"fusion-pixel-12px-zh_hans.{i}.woff2"
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["*"]
        opts.name_IDs = ["*"]
        opts.notdef_outline = True
        f = subset.load_font(str(SRC), opts)
        s = subset.Subsetter(opts)
        s.populate(unicodes=cps)
        s.subset(f)
        subset.save_font(f, str(DIR / name), opts)
        print(f"{name}: {len(cps)} characters, {(DIR / name).stat().st_size // 1024} KB")
        for fam in FAMILIES:
            faces.append(f'@font-face{{font-family:"{fam}";src:url("fonts/fusion-pixel/{name}") format("woff2");'
                         f"font-display:swap;unicode-range:{rng}}}")
    # Latin piece, its own family "Fusion Pixel": for small UI labels, where Fixedsys (an outline font, not on a
    # pixel grid) blurs; this one is pixel-exact at 12px. Body text keeps Fixedsys.
    latin = [(0x20, 0x7E), (0xA0, 0xFF), (0x2010, 0x2027), (0x2030, 0x205E), (0x20AC, 0x20AC)]
    lat = {c for c in cmap if any(a <= c <= b for a, b in latin)}
    name = "fusion-pixel-12px-latin.woff2"
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    f = subset.load_font(str(SRC), opts)
    s = subset.Subsetter(opts)
    s.populate(unicodes=lat)
    s.subset(f)
    subset.save_font(f, str(DIR / name), opts)
    print(f"{name}: {len(lat)} characters, {(DIR / name).stat().st_size // 1024} KB")
    faces.append(f'@font-face{{font-family:"Fusion Pixel";src:url("fonts/fusion-pixel/{name}") format("woff2");'
                 f"font-display:swap;unicode-range:{','.join(f'U+{a:X}-{b:X}' for a, b in latin)}}}")
    CSS.write_text("/* Generated by tools/split_fusion_pixel.py: Fusion Pixel 12px (SIL OFL 1.1): CJK in three "
                   "frequency pieces (as DOS / Fira Code), Latin as \"Fusion Pixel\" for small labels. Loaded without blocking rendering (see _partials/head.html). */\n"
                   + "\n".join(faces) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {CSS.relative_to(THEME)} ({CSS.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
